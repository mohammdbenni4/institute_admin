async function fetchText(url) {
	const res = await fetch(url, { headers: { 'User-Agent': UA } });
	if (!res.ok) throw new Error(`GET ${url} → ${res.status}`);
	return res.text();
}

async function fetchBinary(url) {
	const res = await fetch(url, { headers: { 'User-Agent': UA } });
	if (!res.ok) throw new Error(`GET ${url} → ${res.status}`);
	return Buffer.from(await res.arrayBuffer());
}

/** Download every font referenced by a Google Fonts stylesheet, rewriting the
 *  `src: url(...)` to a local `/fonts/<file>` path. */
async function vendor(source) {
	const css = await fetchText(source.url);
	const urls = [...css.matchAll(/url\((https:\/\/[^)]+)\)/g)].map((m) => m[1]);
	const unique = [...new Set(urls)];

	// Keep only the @font-face rules. Google also ships a `.material-symbols-outlined`
	// helper class, but ours lives in app.css (with the project's weight/fill axes) and
	// must not be overridden.
	let out = (css.match(/@font-face\s*\{[^}]*\}/g) ?? []).join('\n\n');

	let index = 0;
	let bytes = 0;
	for (const remote of unique) {
		const file = `${source.slug}-${index++}.woff2`;
		const data = await fetchBinary(remote);
		await writeFile(join(OUT_DIR, file), data);
		bytes += data.length;
		out = out.split(remote).join(`/fonts/${file}`);
	}
	console.log(`  ${source.name}: ${unique.length} file(s), ${(bytes / 1024).toFixed(1)} KB`);
	return out;
}

async function main() {
	await mkdir(OUT_DIR, { recursive: true });
	console.log('Vendoring webfonts into static/fonts/ …');

	const blocks = [];
	for (const source of SOURCES) blocks.push(await vendor(source));

	const header = [
		'/* GENERATED by `npm run fonts` — do not edit by hand.',
		' *',
		' * Self-hosted webfonts. The app must never request a font over the network:',
		' * a missing icon font makes Material Symbols render their ligature *names* as',
		' * literal text (the spinner spins the word "progress_activity"), and a missing',
		' * Arabic font changes text metrics enough to overlap labels. See',
		' * scripts/fetch-fonts.mjs to add icons. */',
		''
	].join('\n');

	await writeFile(CSS_OUT, `${header}\n${blocks.join('\n')}`);
	console.log(`Wrote ${CSS_OUT}`);

	await writeFile(MANIFEST_OUT, `${JSON.stringify({ icons: ICONS }, null, '\t')}\n`);
	console.log(`Wrote ${MANIFEST_OUT} (${ICONS.length} icons)`);
}

await main();
