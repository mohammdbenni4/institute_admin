// Vendor every webfont the app uses into `static/fonts/` so the APK never touches
// the network for text or icons.
//
// Why this exists: the app used to <link> Google Fonts from `app.html`. On a poor
// connection (or fully offline) the Material Symbols font never arrived, so every
// icon fell back to rendering its *ligature name* as literal text — the spinner
// became the word "progress_activity" rotating on screen, and the Arabic fallback
// font's different metrics made labels overlap. Bundled fonts cannot fail.
//
// Run `npm run fonts` after adding a new icon name to `ICONS` below. The generated
// files are committed; the build itself never hits the network.

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'static', 'fonts');
const CSS_OUT = join(ROOT, 'src', 'lib', 'fonts.css');
// Record of which icons the vendored font actually contains. `npm run icons:check`
// compares it against ICONS below, so editing the list without re-running this
// script fails the build instead of shipping an icon that renders as its own name.
const MANIFEST_OUT = join(OUT_DIR, 'icons.json');

// A modern desktop UA is required or Google serves the much larger .ttf format.
const UA =
	'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

